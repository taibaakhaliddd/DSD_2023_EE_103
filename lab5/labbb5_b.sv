`timescale 1ns / 1ps
module labbb5_b(
    input [1:0] a,
    input [1:0] b,
    input [2:0] S,
    output reg ae, be, c, d, e, f, g, DP,
    output reg [7:0] AN
);

always @(*) begin
    ae = (~a[1] & a[0] & ~b[1] & ~b[0]) |  (~a[1] & ~a[0] & ~b[1] & b[0]) |  (a[1] & a[0] & ~b[1] & b[0]) | (a[1] & ~a[0] & b[1] & b[0]);
    be = (a[1] & b[1] & b[0]) |  (a[0] & b[1] & ~b[0]) |  (a[0] & a[1] & ~b[0]) |  (~a[1] & a[0] & ~b[1] & b[0]);
    c = (~a[1] & ~a[0] & b[1] & b[0])|(a[1] & a[0] & b[1])|(a[1] & a[0] & ~b[0]);
    d = (a[0] & b[1] & b[0]) | (~a[1] & a[0] & ~b[1] & ~b[0]) | (~a[1] & ~a[0] & ~b[1] & b[0]) | (a[1] & ~a[0] & b[1] & ~b[0]);
    e = (b[0] & ~a[1]) |  (~a[1] & a[0] & ~b[1]) | (~b[1] & b[0] & ~a[0]);
    f = (~a[1] & ~a[0] & b[0]) | (~a[1] & b[1] & b[0]) | (~a[1] & ~a[0] & b[1]) |  (a[1] & a[0] & ~b[1] & b[0]);
    g = (~a[1] & ~a[0] & ~b[1]) | (a[1] & a[0] & ~b[1] & ~b[0]) |  (~a[1] & a[0] & b[1] & b[0]);

    DP = 0;
    case (S)
        3'b000: AN = 8'b1111_1110;
        3'b001: AN = 8'b1111_1101;
        3'b010: AN = 8'b1111_1011;
        3'b011: AN = 8'b1111_0111;
        3'b100: AN = 8'b1110_1111;
        3'b101: AN = 8'b1101_1111;
        3'b110: AN = 8'b1011_1111;
        3'b111: AN = 8'b0111_1111;
        default: AN = 8'b1111_1111;
    endcase
end 
endmodule